// Short brand names carry spaces (" dm ", " tk ") to avoid false hits.

const fn d(key: &'static str, name: &'static str, needles: &'static [&'static str], domain: &'static str, color: &'static str, kind: MerchantKind) -> Entry {
    let symbol = match kind {
        K::Supermarket => "cart",
        K::Butcher | K::Restaurant => "fork.knife",
        K::Delivery => "takeoutbag.and.cup.and.straw",
        K::Drugstore => "cross.vial",
        K::Insurance => "shield.lefthalf.filled",
        K::Mobility => "tram",
        K::Fuel => "fuelpump",
        K::Streaming => "play.tv",
        K::Telecom => "antenna.radiowaves.left.and.right",
        K::Utilities => "bolt",
        K::OnlineShop => "bag",
        K::Electronics => "desktopcomputer",
        K::Games => "gamecontroller",
        K::Fitness => "figure.run",
        K::Travel => "airplane",
        K::Bank | K::Broker => "building.columns",
        K::EtfIssuer | K::Etf => "chart.line.uptrend.xyaxis",
        _ => "",
    };
    Entry { key, name, needles, domain, color, symbol, kind, isin: "", wkn: "" }
}

