import XCTest
@testable import GiroCrabUI

/// Opt-in clipboard check when the transfer form opens (#663).
final class ClipboardPaymentCheckTests: XCTestCase {
    private func check(draftEmpty: Bool = true, changeCount: Int = 7, lastHandled: Int? = nil) -> Bool {
        ClipboardPaymentCheck.shouldCheck(draftEmpty: draftEmpty, changeCount: changeCount, lastHandled: lastHandled)
    }

    func testSettingIsOffByDefault() {
        XCTAssertFalse(ClipboardPaymentCheck.enabledDefault)
    }

    func testChecksOnlyWhenAllConditionsHold() {
        XCTAssertTrue(check())
        XCTAssertTrue(check(lastHandled: 6))
        XCTAssertFalse(check(draftEmpty: false), "filled draft")
        XCTAssertFalse(check(changeCount: 7, lastHandled: 7), "content already offered or ignored")
    }

    func testDraftCountsAsFilled() {
        XCTAssertTrue(ClipboardPaymentCheck.isEmpty(TransferDraft(accountID: 1), ownTransfer: false))
        XCTAssertTrue(ClipboardPaymentCheck.isEmpty(TransferDraft(name: "  "), ownTransfer: false))
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(), ownTransfer: true), "own transfer")
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(name: "Anna"), ownTransfer: false))
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(iban: "DE89"), ownTransfer: false))
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(bic: "COBADEFFXXX"), ownTransfer: false))
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(amountText: "12"), ownTransfer: false))
        XCTAssertFalse(ClipboardPaymentCheck.isEmpty(TransferDraft(purpose: "Miete"), ownTransfer: false))
        // the PIN or the execution mode is no recipient data
        XCTAssertTrue(ClipboardPaymentCheck.isEmpty(TransferDraft(pin: "12345", instant: true), ownTransfer: false))
    }

    func testSkipsConcealedAndTransientEntries() {
        XCTAssertTrue(ClipboardPaymentCheck.isSkipped(types: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
        XCTAssertTrue(ClipboardPaymentCheck.isSkipped(types: ["org.nspasteboard.TransientType"]))
        XCTAssertTrue(ClipboardPaymentCheck.isSkipped(types: ["org.nspasteboard.AutoGeneratedType"]))
        XCTAssertFalse(ClipboardPaymentCheck.isSkipped(types: ["public.utf8-plain-text"]))
    }

    func testNeutralBannerOnlyForTextWithANumber() {
        XCTAssertTrue(ClipboardPaymentCheck.offersText(for: [.number]))
        XCTAssertFalse(ClipboardPaymentCheck.offersText(for: [.probableWebURL]), "URL only")
        XCTAssertFalse(ClipboardPaymentCheck.offersText(for: []), "a word, nothing detected")
        // the whole text is one web address; digits in its path are no payment
        XCTAssertFalse(ClipboardPaymentCheck.offersText(for: [.number, .probableWebURL]), "URL + number")
    }

    func testFilterKeepsAParsedPayment() async {
        let payment = ClipboardPaymentCheck.offer(for: .demo)
        let filtered = await ClipboardPaymentCheck.filtered(payment)
        XCTAssertEqual(filtered, payment)
        let none = await ClipboardPaymentCheck.filtered(nil)
        XCTAssertNil(none)
    }

    func testMasksIBAN() {
        XCTAssertEqual(ClipboardPaymentCheck.maskedIBAN("DE89 3704 0044 0532 0130 00"), "DE89 •••• •••• 3000")
        XCTAssertEqual(ClipboardPaymentCheck.maskedIBAN("de89370400440532013000"), "DE89 •••• •••• 3000")
        XCTAssertEqual(ClipboardPaymentCheck.maskedIBAN("DE89"), "••••")
    }

    func testOffersOnlyAValidIBAN() {
        let found = PaymentParser.parseText("Stadtwerke München\nIBAN DE89 3704 0044 0532 0130 00\nBetrag 85,00 EUR")
        XCTAssertEqual(ClipboardPaymentCheck.offer(for: found),
                       .payment(found, summary: ClipboardPaymentCheck.summary(found)))
        XCTAssertNil(ClipboardPaymentCheck.offer(for: PaymentParser.parseText("IBAN DE00 3704 0044 0532 0130 00")),
                     "wrong checksum")
        XCTAssertNil(ClipboardPaymentCheck.offer(for: PaymentParser.parseText("Einkaufsliste: Milch, Brot")))
    }

    func testBannerSummaryHidesTheMiddleOfTheIBAN() {
        let p = ParsedPayment(name: "Stadtwerke München", iban: "DE89370400440532013000", amountText: "85.00")
        let s = ClipboardPaymentCheck.summary(p)
        XCTAssertTrue(s.hasPrefix("DE89 •••• •••• 3000 · Stadtwerke München · "))
        XCTAssertFalse(s.contains("0532"))
    }

    func testAcceptFillsOnlyEmptyFields() {
        var d = TransferDraft(name: "Eigener Name", amountText: "")
        let p = ParsedPayment(name: "Stadtwerke München", iban: "DE89370400440532013000", amountText: "85.00", purpose: "Abschlag")
        p.apply(to: &d, onlyEmpty: true)
        XCTAssertEqual(d.name, "Eigener Name")
        XCTAssertEqual(d.iban, "DE89 3704 0044 0532 0130 00")
        XCTAssertEqual(d.amountText, "85.00")
        XCTAssertEqual(d.purpose, "Abschlag")

        // the paste button keeps overwriting
        p.apply(to: &d)
        XCTAssertEqual(d.name, "Stadtwerke München")
    }
}
