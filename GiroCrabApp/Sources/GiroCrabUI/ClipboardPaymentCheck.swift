/// Opt-in look at the clipboard when an empty transfer form opens (#663). Off by default, per device.
/// The text is read only where the system allows it without a prompt (macOS) or on a tap (iOS
/// `PasteButton`); it is parsed in memory and never stored or logged. Only the pasteboard's
/// `changeCount` is remembered, so the same content is offered once.
enum ClipboardPaymentCheck {
    static let enabledKey = "transfer.clipboardCheck"
    static let enabledDefault = false
    /// Longer text is no payment slip; parsing it would only delay opening the sheet.
    static let maxTextBytes = 8 * 1024

    /// What the banner offers.
    enum Offer: Equatable {
        /// Read silently and parsed: a payment with a valid IBAN, and the banner's masked summary of it.
        case payment(ParsedPayment, summary: String)
        /// Some text, read only on a click or tap.
        case text
    }

    /// Marked by password managers and clipboard tools as secret or short-lived (nspasteboard.org).
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    static func isSkipped(types: [String]) -> Bool {
        types.contains { skippedTypes.contains($0) }
    }

    /// Nothing typed or prefilled yet (template, link, booking, own transfer).
    static func isEmpty(_ d: TransferDraft, ownTransfer: Bool) -> Bool {
        !ownTransfer && TransferDraft.paymentFields.allSatisfy(d.isBlank)
    }

    static func shouldCheck(draftEmpty: Bool, changeCount: Int, lastHandled: Int?) -> Bool {
        draftEmpty && changeCount != lastHandled
    }

    /// "DE89 •••• •••• 3000": country, check digits and the last four characters.
    static func maskedIBAN(_ iban: String) -> String {
        let groups = TransferSheetView.groupedIBAN(iban).split(separator: " ")
        guard groups.count > 2, let first = groups.first else { return String(repeating: "•", count: groups.joined().count) }
        return "\(first) •••• •••• \(groups.joined().suffix(4))"
    }

    /// The banner's offer for the parsed clipboard text: only a payment with a valid IBAN
    /// (the core sets `iban` only when its checksum is right).
    static func offer(for parsed: ParsedPayment) -> Offer? {
        parsed.iban == nil ? nil : .payment(parsed, summary: summary(parsed))
    }

    /// Masked IBAN, recipient and amount where found.
    static func summary(_ p: ParsedPayment) -> String {
        [p.iban.map(maskedIBAN),
         p.name,
         p.amountText.flatMap { try? parseAmountToCents(text: $0) }.map { Money.format($0) }]
            .compactMap { $0 }.joined(separator: " · ")
    }

    /// Looks at the clipboard unless this content was already looked at (`lastHandled`, updated here).
    /// Reads the text only where that is silent.
    @MainActor static func check(draftEmpty: Bool, lastHandled: inout Int?) -> Offer? {
        #if os(macOS)
        let pb = NSPasteboard.general
        #else
        let pb = UIPasteboard.general
        #endif
        let count = pb.changeCount
        guard shouldCheck(draftEmpty: draftEmpty, changeCount: count, lastHandled: lastHandled) else { return nil }
        lastHandled = count // offered (or skipped) once per content
        #if os(macOS)
        let types = pb.types?.map(\.rawValue) ?? []
        guard types.contains(NSPasteboard.PasteboardType.string.rawValue), !isSkipped(types: types) else { return nil }
        guard readsSilently(pb) else { return .text }
        guard let text = pb.string(forType: .string), text.utf8.count <= maxTextBytes else { return nil }
        return offer(for: PaymentParser.parseText(text))
        #else
        // `types` and `hasStrings` do not trigger the "Allow Paste" prompt; the text is read by the PasteButton.
        guard pb.hasStrings, !isSkipped(types: pb.types) else { return nil }
        return .text
        #endif
    }

    /// What the system's pattern detection found in the clipboard text (read without the content).
    enum DetectedPattern: Hashable { case number, probableWebURL }

    /// The neutral banner only for text with a number in it (IBAN, amount) that is not just a web
    /// address. `probableWebURL` means the whole text looks like one address, so digits in its path
    /// or query do not make it a payment: URL + number → no banner.
    static func offersText(for detected: Set<DetectedPattern>) -> Bool {
        detected.contains(.number) && !detected.contains(.probableWebURL)
    }

    /// Filters the neutral `.text` offer by the system's pattern detection, which neither reads the
    /// text into the app nor shows the paste prompt. Detection unavailable or failing: no banner.
    static func filtered(_ offer: Offer?) async -> Offer? {
        guard offer == .text else { return offer }
        guard let detected = await detectedPatterns() else { return nil }
        return offersText(for: detected) ? offer : nil
    }

    @MainActor private static func detectedPatterns() async -> Set<DetectedPattern>? {
        #if os(macOS)
        // before 15.4 the text was read silently, so `.text` is never offered there
        guard #available(macOS 15.4, *) else { return nil }
        let pb = NSPasteboard.general
        guard let found = try? await pb.detectedPatterns(for: [\.number, \.probableWebURL]) else { return nil }
        #else
        let pb = UIPasteboard.general
        guard let found = try? await pb.detectedPatterns(for: [\.number, \.probableWebURL]) else { return nil }
        #endif
        var detected: Set<DetectedPattern> = []
        if found.contains(\.number) { detected.insert(.number) }
        if found.contains(\.probableWebURL) { detected.insert(.probableWebURL) }
        return detected
    }

    #if os(macOS)
    /// Before macOS 15.4 reading is silent; since then only when the user allowed it for good.
    private static func readsSilently(_ pb: NSPasteboard) -> Bool {
        if #available(macOS 15.4, *) { return pb.accessBehavior == .alwaysAllow }
        return true
    }
    #endif
}

/// The banner above the transfer form. "Übernehmen" fills only empty fields.
struct ClipboardPaymentBanner: View {
    let offer: ClipboardPaymentCheck.Offer
    let apply: (ParsedPayment) -> Void
    let ignore: () -> Void

    var body: some View {
        HStack(alignment: .center, spacing: 10) {
            Image(systemName: "doc.on.clipboard").foregroundStyle(Theme.accent)
            VStack(alignment: .leading, spacing: 2) {
                switch offer {
                case .payment(_, let summary):
                    Text("Zahlung in der Zwischenablage").appFont(.callout, weight: .semibold)
                    Text(summary)
                        .appFont(.caption, monospacedDigit: true)
                        .foregroundStyle(Theme.secondary)
                        .lineLimit(2)
                        .sensitive([.personal, .amounts])
                case .text:
                    Text("Zwischenablage enthält Text – als Zahlung übernehmen?").appFont(.callout)
                        .fixedSize(horizontal: false, vertical: true)
                }
            }
            Spacer(minLength: 4)
            Button("Ignorieren", action: ignore)
            acceptButton
        }
        .controlSize(.small)
        .padding(10)
        .background(Theme.accent.opacity(0.12), in: RoundedRectangle(cornerRadius: 10))
    }

    @ViewBuilder private var acceptButton: some View {
        switch offer {
        case .payment(let p, _):
            Button("Übernehmen") { apply(p) }.buttonStyle(.borderedProminent)
        case .text:
            #if os(macOS)
            // a click is a user interaction: a privacy prompt is acceptable here
            Button("Übernehmen") { apply(PaymentParser.parseClipboard()) }
                .buttonStyle(.borderedProminent)
            #else
            PaymentPasteButton { apply(PaymentParser.parseText($0)) }
            #endif
        }
    }
}

#if os(iOS)
/// The system's paste button: reads the clipboard on a tap, without the "Allow Paste" prompt.
struct PaymentPasteButton: View {
    let onText: (String) -> Void

    var body: some View {
        PasteButton(payloadType: String.self) { strings in
            Task { @MainActor in onText(strings.joined(separator: "\n")) }
        }
    }
}
#endif
